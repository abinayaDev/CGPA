const fs = require('fs');
const path = require('path');

// Read API URL from environment variables (set on Vercel as API_BASE_URL)
const apiUrl = process.env.API_BASE_URL || process.env.PUBLIC_API_BASE_URL || '';

const outDir = path.join(__dirname, '..', 'static');
const outPath = path.join(outDir, 'config.js');

const content = `// Auto-generated by build\nconst API_BASE_URL = "${apiUrl}";\n`;

if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

fs.writeFileSync(outPath, content, { encoding: 'utf8' });
console.log(`Wrote ${outPath} with API_BASE_URL=${apiUrl}`);
